// The smallest host the Workflow SDK supports: its standalone build (`workflow build`, run by the
// test's global setup) mounted on a Hono server. The Postgres World's queue delivers messages to
// the flow route over loopback HTTP. Run as its own process so the test can kill it with SIGKILL.
import { serve } from "@hono/node-server";
import { Hono } from "hono";
import { getHookByToken, getRun, resumeHook, start } from "workflow/api";
import { getWorld, healthCheck } from "workflow/runtime";
import { z } from "zod";
import { keyRequests } from "./world.ts";

interface FlowModule {
  POST(request: Request): Promise<Response>;
}

/** A workflow as the build's manifest lists it; `start()` takes it in place of the function. */
const WorkflowMetadata = z.object({ workflowId: z.string() });

/** The workflows of `workflows/markers.ts`, the file the host starts its runs from. */
const MarkersWorkflows = z.object({
  markers: WorkflowMetadata.optional(),
  bodyAttribute: WorkflowMetadata.optional(),
});

/** The part of the build's manifest the host reads. */
const ManifestModule = z.object({
  default: z.object({
    workflows: z.object({ "workflows/markers.ts": MarkersWorkflows.optional() }),
  }),
});

// Generated by the build, so it is loaded by path rather than imported statically.
const generated = new URL("./.well-known/workflow/v1/", import.meta.url);

// SAFETY: flow.mjs is the route module `workflow build` writes (global-setup.ts runs it before
// any host starts); it ends `export { GET, HEAD, OPTIONS, POST }` with
// `POST = workflowEntrypoint(...)`, the SDK's handler from a Request to a Promise<Response>.
const flow = (await import(new URL("flow.mjs", generated).href)) as FlowModule;

const manifest = ManifestModule.parse(
  await import(new URL("manifest.json", generated).href, { with: { type: "json" } }),
).default;

const markersWorkflow = manifest.workflows["workflows/markers.ts"]?.markers;

const bodyAttributeWorkflow = manifest.workflows["workflows/markers.ts"]?.bodyAttribute;

if (!markersWorkflow || !bodyAttributeWorkflow) {
  throw new Error("harness: the build lacks a workflow of workflows/markers.ts");
}

/** The error's message, and the name and message of it and each of its causes. */
function failure(cause: unknown) {
  const chain: { name: string; message: string }[] = [];

  for (let at = cause; at instanceof Error && chain.length < 8; at = at.cause) {
    chain.push({ name: at.name, message: at.message });
  }

  return { error: cause instanceof Error ? cause.message : String(cause), chain };
}

const app = new Hono()
  .post("/.well-known/workflow/v1/flow", (c) => flow.POST(c.req.raw))
  .post("/start", async (c) => {
    const { nonce, tenant } = await c.req.json<{ nonce: string; tenant?: string }>();

    // The SDK passes its whole start options bag to the World at run creation; the extra
    // option is how the encrypting World learns the tenant. Its type does not declare it.
    // M9 is a run attribute given at start. `kind` is the one key the harness World lists as
    // readable.
    const attributes = { note: `OSMARK9_${nonce}`, kind: "proof" };
    const options = tenant ? { attributes, osTenantId: tenant } : { attributes };

    try {
      const run = await start(markersWorkflow, [{ nonce, m1: `OSMARK1_${nonce}` }], options);

      return c.json({ runId: run.runId });
    } catch (error) {
      return c.json(failure(error), 500);
    }
  })
  .post("/start-body-attribute", async (c) => {
    const { marker } = await c.req.json<{ marker: string }>();

    try {
      const run = await start(bodyAttributeWorkflow, [{ marker }], {});

      return c.json({ runId: run.runId });
    } catch (error) {
      return c.json(failure(error), 500);
    }
  })
  .post("/resume", async (c) => {
    const { token, m5 } = await c.req.json<{ token: string; m5: string }>();

    try {
      return c.json({ runId: (await resumeHook(token, { m5 })).runId });
    } catch (error) {
      return c.json(failure(error), 500);
    }
  })
  .get("/hook/:token", async (c) => {
    try {
      const hook = await getHookByToken(c.req.param("token"));

      return c.json({ runId: hook.runId, metadata: await hook.metadata });
    } catch (error) {
      return c.json(failure(error), 500);
    }
  })
  .get("/result/:runId", async (c) => {
    try {
      return c.json({ value: await getRun(c.req.param("runId")).returnValue });
    } catch (error) {
      return c.json(failure(error), 500);
    }
  })
  .get("/stream/:runId", async (c) => {
    try {
      const reader = getRun(c.req.param("runId")).getReadable<string>().getReader();
      const first = await reader.read();
      reader.releaseLock();

      return c.json({ chunk: first.value ?? null });
    } catch (error) {
      return c.json(failure(error), 500);
    }
  })
  .post("/probe", async (c) => {
    // A health check that names a run, as `start()` sends to another deployment before
    // creating a run there. The responder asks its World for that run's key.
    const { runId } = await c.req.json<{ runId: string }>();
    const result = await healthCheck(await getWorld(), { runId, timeout: 20_000 });

    return c.json({ healthy: result.healthy, publicKey: result.encryptionPublicKey ?? null });
  })
  .get("/keylog", (c) => c.json({ requests: keyRequests() }));

const port = Number(process.env.PORT);

serve({ fetch: app.fetch, port, hostname: "127.0.0.1" }, async () => {
  const world = await getWorld();

  try {
    await world.start?.();
    process.stdout.write(`READY ${port}\n`);
  } catch (error) {
    process.stdout.write(`START_FAILED ${JSON.stringify(failure(error))}\n`);
  }
});
